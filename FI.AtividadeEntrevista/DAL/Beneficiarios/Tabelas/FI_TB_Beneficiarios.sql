-- Tabela de beneficiários do cliente
-- CPF gravado apenas com dígitos (11 caracteres) e único por cliente

CREATE TABLE BENEFICIARIOS
(
    ID        BIGINT       IDENTITY (1, 1) NOT NULL PRIMARY KEY,
    CPF       VARCHAR (11) NOT NULL,
    NOME      VARCHAR (50) NOT NULL,
    IDCLIENTE BIGINT       NOT NULL,

    CONSTRAINT FK_BENEFICIARIOS_CLIENTES FOREIGN KEY (IDCLIENTE) REFERENCES CLIENTES (ID) ON DELETE CASCADE,
    CONSTRAINT UQ_BENEFICIARIOS_IDCLIENTE_CPF UNIQUE (IDCLIENTE, CPF)
);
GO
